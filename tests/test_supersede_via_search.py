"""
================================================================================
 TEST_SUPERSEDE_VIA_SEARCH.PY — Обновление, сказанное СВОИМИ СЛОВАМИ
================================================================================
Прежний путь искал устаревшее перебором всех узлов с косинусом >= 0.8
между предложениями целиком. Это сломано не числом, а замыслом:
противоречие — "та же тема, ДРУГОЕ значение", поэтому чем сильнее
изменение, тем ниже сходство предложений и тем вернее обновление
проскочит. Доказательство противоречия вычиталось из доказательства
связанности.

Замер против 0.8:
    "мою собаку зовут Рекс" -> "... Бобик"             0.923  ловит
    "моя собака зовут Рекс" -> "мою собаку ТЕПЕРЬ..."  0.722  мимо
    "я живу в Москве" -> "я ПЕРЕЕХАЛ в Питер"          0.369  мимо

Первая пара — пример из докстринга самого механизма. То есть он был
откалиброван ровно под то, что про него написано.

Новый путь берёт кандидатов из ОБЫЧНОГО ПОИСКА, который смешивает слова,
нечёткое сходство и смысл, а не полагается на один косинус. Поиск нашёл
старый узел во всех шести проверенных случаях.

Итог замера: 3 из 6 против 5 из 6, ложных срабатываний ноль у обоих.

ЧЕСТНЫЙ ПРЕДЕЛ, и он проверяется отдельным тестом ниже: шестой случай не
берётся ничем. "Живу в Москве" и "переехал в Питер" не делят ни одного
слова, и никакая мера сходства строк их не свяжет. Нужно знать, что
"переехал" отменяет "живу", а такого знания у библиотеки нет.
================================================================================
"""

import pytest

from selectivemem import Memory, MemorySettings

NOISE = [
    "вчера был сильный дождь",
    "в магазине продают свежий хлеб",
    "во дворе растёт высокое дерево",
    "чайник кипит примерно пять минут",
]


def _memory(threshold: float = 0.5):
    return Memory(
        ":memory:",
        settings=MemorySettings(contradiction_search_threshold=threshold),
    )


def _superseded_contexts(memory, old: str, new: str):
    memory.observe(old, emotion=0.9)
    for noise in NOISE:
        memory.observe(noise, emotion=0.9)
    return [s.context.lower() for s in memory.graph.find_superseded(new)]


@pytest.mark.parametrize("old,new", [
    ("мою собаку зовут Рекс", "мою собаку зовут Бобик"),
    ("моя собака зовут Рекс", "мою собаку теперь зовут Бобик"),
    ("мой любимый цвет синий", "мой любимый цвет красный"),
    ("я работаю программистом", "я теперь работаю дизайнером"),
    ("мой рейс в четверг", "рейс перенесли на субботу"),
])
def test_update_in_the_users_own_words_is_caught(old, new):
    """Человек сообщает об изменении как ему удобно, а не по шаблону."""
    memory = _memory()
    contexts = _superseded_contexts(memory, old, new)
    assert any(old.lower() in c for c in contexts), (
        f"обновление {new!r} не опознано как замена {old!r}"
    )
    memory.close()


def test_unrelated_memories_are_never_touched():
    """
    Цена ошибки несимметрична: пропустить противоречие дешевле, чем
    ослабить верное воспоминание. Ни одна посторонняя запись не должна
    попасть под вытеснение.
    """
    memory = _memory()
    contexts = _superseded_contexts(
        memory, "мою собаку зовут Рекс", "мою собаку зовут Бобик"
    )
    for noise in NOISE:
        assert not any(noise.lower() in c for c in contexts), (
            f"постороннее воспоминание {noise!r} попало под вытеснение"
        )
    memory.close()


def test_a_plain_repetition_is_not_a_new_version():
    """Повтор должен ПОДКРЕПЛЯТЬ узел, а не вытеснять его."""
    memory = _memory()
    contexts = _superseded_contexts(
        memory, "мою собаку зовут Рекс", "мою собаку зовут Рекс"
    )
    assert not contexts, "дословный повтор принят за новую версию"
    memory.close()


def test_the_known_limit_is_recorded_not_hidden():
    """
    Отрицательный результат, который не выбрасывается. "Живу в Москве" и
    "переехал в Питер" не делят ни одного слова: сходство 0.369, поиск
    ставит старый узел вровень с посторонними (0.338 против 0.348).
    Механизм этого не берёт, и это записано здесь, чтобы не выглядело
    случайной регрессией, когда кто-нибудь заметит.
    """
    memory = _memory()
    contexts = _superseded_contexts(memory, "я живу в Москве", "я переехал в Питер")
    assert not any("москве" in c for c in contexts), (
        "случай неожиданно заработал — обновите этот тест и AUDIT.md, "
        "предел механизма сдвинулся"
    )
    memory.close()


def test_zero_threshold_restores_the_old_path():
    """Путь отката должен работать: ноль возвращает прежнее поведение."""
    memory = _memory(threshold=0.0)
    contexts = _superseded_contexts(
        memory, "моя собака зовут Рекс", "мою собаку теперь зовут Бобик"
    )
    assert not any("рекс" in c for c in contexts), (
        "прежний путь не восстановился: он этот случай не ловил"
    )
    memory.close()
