"""
================================================================================
 SETTINGS.PY — Settings of the memory core
================================================================================
The third step of extracting the package: the core NO LONGER READS the
application's global config.

memory/* used to import config.py — a thousand-line module holding a
Telegram token, prompts and persona settings. Unacceptable for a library
installed via pip: it must carry its own configuration rather than depend
on one particular application's file.

The defaults are the values calibrated by measurement (see AUDIT.md). An
application may pass its own:

    graph = MemoryGraph(db=db, settings=MemorySettings(decay_rate=0.02))

or build them from its config wholesale:

    graph = MemoryGraph(db=db, settings=MemorySettings.from_module(config))

This file was GENERATED from config.py so the values are guaranteed to
match: retyping seventy constants by hand is a reliable way to change
something without noticing. test_settings.py checks them on every run.
================================================================================
"""

from dataclasses import dataclass, fields
from typing import Any


@dataclass
class MemorySettings:
    """Memory core parameters. Names mirror config.py, lower-cased."""

    age_t0: float = 25200.0
    babbling_syllable_pool_size: int = 30
    # ПОРОГ НЕ ИЗМЕНИЛСЯ ПРИ СМЕНЕ ФОРМЫ ГЕЙТА, и это следствие
    # нормировки: при нулевой эмоции нормированное произведение даёт
    # ровно 0.5·новизна, как и прежнее среднее. Для тех, кто эмоцию не
    # передаёт, не меняется ничего.
    base_plasticity_threshold: float = 0.25
    # Насколько эмоция УСИЛИВАЕТ новизну в решении о записи.
    #
    # Прежняя формула — среднее: (эмоция + удивление) / 2. Такой арифметики
    # в биологии нет: норадреналин умножает пластичность, которую новизна
    # уже открыла, а не складывается с ней. Из-за среднего событие
    # страшное-но-привычное и безразличное-но-небывалое оценивались
    # одинаково.
    #
    # Форма выбрана так, чтобы новизна оставалась ОСНОВАНИЕМ:
    #     плотность = удивление * (1 + эмоция * этот множитель)
    # Чистое произведение обнулило бы гейт у всех, кто не передаёт эмоцию,
    # а по умолчанию она 0.0 — то есть у обычного библиотечного
    # пользователя память перестала бы писать вообще.
    #
    # Ноль возвращает прежнее среднее.
    gate_emotion_gain: float = 1.0
    # Эмоция от этого уровня пишет САМА ПО СЕБЕ, минуя порог плотности.
    #
    # Нужно из-за формы гейта: умножение не даёт эмоции спасти привычное,
    # потому что произведение с околонулевой новизной остаётся
    # околонулевым. Биологически верно, но продукт обещает, что
    # emotion=1.0 («пользователь сказал запомни») сработает всегда.
    #
    # В мозге этот путь тоже отдельный: вспышечные воспоминания возникают
    # не от новизны обстановки, а оттого что миндалина при сильном
    # возбуждении модулирует гиппокамп напрямую, минуя обычный порог.
    #
    # 0.0 выключает второй вход.
    # ЕДИНИЦА, А НЕ 0.9, и это не придирка. README обещает ровно одно:
    # emotion=1.0 означает «пользователь сказал запомни». Всё, что ниже, —
    # обычная значимость, и она должна проходить общий путь, иначе второй
    # вход открыт всегда и форма гейта не значит ничего.
    #
    # Первая попытка ставила 0.9 — и стенд, подающий ровно 0.9, сводил
    # правку к нулю: заряженное-привычное писалось через обход.
    gate_emotion_override: float = 1.0
    concept_max_similar_links: int = 2
    concept_node_weight: float = 0.7
    concept_similarity_edge_weight: float = 0.25
    concept_similarity_link_threshold: float = 0.35
    concept_user_edge_weight: float = 0.4
    contradiction_correction_relief: float = 0.15
    contradiction_repeat_threshold: float = 0.85
    contradiction_stability_factor: float = 0.25
    contradiction_topic_threshold: float = 0.8
    # Ненулевое значение включает НОВЫЙ путь поиска устаревшего: кандидаты
    # берутся из обычного поиска, а не перебором всех узлов с высоким
    # порогом косинуса. Смысл замены — в графе, а не в числе.
    #
    # Прежний путь сравнивал предложения целиком и требовал 0.8. Но
    # противоречие — это "та же тема, ДРУГОЕ значение", поэтому чем сильнее
    # изменение, тем меньше сходство предложений и тем вернее обновление
    # проскочит. Доказательство противоречия вычиталось из доказательства
    # связанности.
    #
    # Замер против порога 0.8:
    #   "мою собаку зовут Рекс" -> "... Бобик"            0.923  ловит
    #   "моя собака зовут Рекс" -> "мою собаку ТЕПЕРЬ..." 0.722  мимо
    #   "я живу в Москве" -> "я ПЕРЕЕХАЛ в Питер"         0.369  мимо
    # Первая пара — пример из докстринга самого механизма.
    #
    # Через поиск: пять обновлений из шести отделяются с запасом (худшее
    # настоящее 0.642 против лучшего постороннего 0.433). Шестое —
    # "Москва/Питер" — не отделяется ничем, там нет общих слов вовсе.
    #
    # Ноль возвращает прежний путь.
    # ОСТАЁТСЯ ВЫКЛЮЧЕННЫМ, и это отмена собственной рекомендации.
    #
    # Путь через поиск ловит 5 обновлений из 6 против 3 у прежнего, и
    # первая проверка не нашла ложных срабатываний. Проверка была
    # НЕПОЛНОЙ: мерились истинные обновления и далёкий шум, но не близкие
    # СОВМЕСТИМЫЕ факты — а ломается он именно там.
    #
    #   ОБНОВЛЕНИЕ  0.818  "мою собаку зовут Бобик"
    #   ОБНОВЛЕНИЕ  0.547  "мою собаку теперь зовут Бобик"
    #   СОВМЕСТИМО  0.710  "я люблю кофе"      (после "я люблю чай")
    #   СОВМЕСТИМО  0.669  "у меня есть собака" (после "у меня есть кошка")
    #   СОВМЕСТИМО  0.603  "у меня есть сестра" (после "у меня есть брат")
    #
    # Порога, разделяющего эти группы, НЕ СУЩЕСТВУЕТ: обновление на 0.547
    # ниже совместимого на 0.603. Пересечение слов тоже не разделяет —
    # обе группы в диапазоне 0.5-0.75.
    #
    # Различие семантическое: "мою собаку зовут Бобик" ЗАМЕНЯЕТ, "у меня
    # есть собака" ДОБАВЛЯЕТ. Зависит от того, однозначно ли поле, а этого
    # знания у библиотеки нет.
    #
    # Цена ошибок несимметрична — пропустить противоречие дешевле, чем
    # ослабить верный факт, — поэтому по умолчанию оставлен прежний,
    # осторожный путь. Приложение, готовое платить порчей за полноту,
    # включает 0.5 осознанно.
    contradiction_search_threshold: float = 0.0
    # Сколько кандидатов брать из поиска при проверке на устаревание.
    contradiction_candidates: int = 5
    # Минимальная доля общих значимых слов, без которой вытеснение не
    # срабатывает. ЗАЩИТА ОТ ЧУЖОГО КОДИРОВЩИКА, и она измерена.
    #
    # Замер: русская модель (та, что в пакете) на английском тексте даёт
    # "my dog is called Rex" против "the price of bread went up" косинус
    # 0.808 при пороге вытеснения 0.8. Порог сидит внутри шума, и память
    # начинает ослаблять факт про собаку, потому что подорожал хлеб. На
    # тексте LongMemEval это давало 3080 срабатываний на 79 записей —
    # сорок ослаблений на каждую запись, молча.
    #
    # Проверки "хотя бы одно общее слово" НЕ ХВАТИЛО: _extract_keywords
    # отсекает РУССКИЕ стоп-слова, поэтому на английском "the", "is",
    # "my" остаются значимыми и пересечение всегда больше нуля.
    #
    # Откуда 0.25. Посторонние английские пары под русской моделью:
    # медиана 0.080, выше 0.25 только 14%. Настоящие обновления по-русски:
    # 0.25, 0.33, 0.50, 0.75, 0.75 — то есть порог сохраняет пять из шести
    # (шестое, "Москва/Питер", не берётся ничем и записано отдельным
    # тестом как известный предел).
    # Насколько привычным может быть общее слово, чтобы поправка ещё
    # считалась поправкой. Единица выключает проверку.
    #
    # Привычность берётся как максимум из опыта (граф языка) и априорного
    # знания о частотности (lexicon.py). Без второго проверка не работает
    # в начале разговора, а именно там она и нужна: в двадцати трёх
    # репликах редко ВСЁ.
    contradiction_subject_familiarity: float = 0.7
    contradiction_min_overlap: float = 0.25
    # РАЗДЕЛЕНИЕ ОБРАЗОВ: сколько похожих узлов ещё позволяет считать
    # новый текст поправкой к одному из них.
    #
    # Поправка заменяет ОДНО конкретное воспоминание. Если на новый текст
    # одинаково отзывается десяток узлов, вопрос "какой из них исправлен"
    # ответа не имеет, и правильный ответ — не трогать никого.
    #
    # Замер, ради которого это сделано: 200 почти-двойников при записи
    # давали 6078 вытеснений — каждая запись "исправляла" тридцать чужих
    # узлов. Сильнее всех страдали настоящие факты: они похожи на всех
    # своих двойников разом, поэтому сила у них падала до 0.0000 при
    # 0.0292 у копий. Оригинал оказывался слабее собственных двойников.
    #
    # В мозге это делает зубчатая извилина, и делает НА ВХОДЕ: похожие
    # входы получают непохожие коды ДО записи, чтобы потом не мешать друг
    # другу. Мы боролись с последствием при извлечении.
    #
    # 0 выключает проверку.
    pattern_separation_limit: int = 2

    # --- КОРА ОБОБЩАЕТ ---
    #
    # Сколько раз тема должна повториться, чтобы кора вывела из неё факт.
    # 0 выключает.
    #
    # БИОЛОГИЯ. Кора не хранит события — она копит статистику по ним и
    # выводит устойчивое: сто разговоров про кофе дают знание «человек
    # любит кофе», не привязанное ни к одному разговору. Гиппокамп помнит
    # «в четверг Лиза сказала про арахис», кора знает «арахис — про
    # аллергию».
    #
    # У НАС СИГНАЛ ПОВТОРЯЕМОСТИ УЖЕ ЕСТЬ И ВЫБРАСЫВАЕТСЯ. Разделение
    # образов срабатывает ровно тогда, когда на новый текст откликается
    # десяток похожих — то есть тема повторяется. Сейчас мы в этом случае
    # просто никого не вытесняем, и на этом всё.
    #
    # Теперь тот же случай растит корковому факту число встреч. Факт
    # ищется наравне с эпизодами, но его сила растёт не от важности
    # события, а от ТОГО, СКОЛЬКО РАЗ тема возвращалась.
    cortex_fact_threshold: int = 3
    # Насколько сила коркового факта растёт с каждой встречей. Логарифм, а
    # не линейно: десятое повторение добавляет меньше второго — так и
    # учится кора.
    cortex_fact_strength: float = 0.35
    # Какую долю записей может занимать слово, чтобы всё ещё считаться
    # темой. Слово, встречающееся у половины эпизодов, не различает
    # ничего — это фон, а не тема.
    cortex_fact_max_share: float = 0.5
    # Насколько привычным СЛОВОМ тема быть уже не может.
    #
    # Организм ведёт граф языка с весами: сколько раз слово встречалось,
    # с насыщением к единице. Слово, знакомое назубок, не может быть тем,
    # чем данный случай отличается от прочих, — оно есть везде.
    #
    # Замер (стенд compare_gist, 300 реплик канцелярского наполнителя):
    #     виолончель 0.264  пенициллин 0.264  марафон 0.186
    #     утром 1.000       обедом 1.000      перенёс 1.000
    # Разделение полное; 0.7 стоит посередине зазора.
    #
    # Прежде на этом месте была доля эпизодов, содержащих слово, — она не
    # разделяет вовсе: «рано утром» сидит в пяти процентах записей.
    cortex_theme_max_familiarity: float = 0.7
    # Сколько выведенных тем пересматривать за один сон. Пересмотр снимает
    # то, что оказалось оборотом речи: проверка на редкость идёт в момент
    # вывода, а тогда организм знает мало и канцелярит ему в новинку.
    cortex_review_limit: int = 200


    # --- ПОДКРЕПЛЕНИЕ ПО ПОСЛЕДСТВИЮ ---
    #
    # Насколько слабеют узлы, которые были выданы, а следом пришёл ТОТ ЖЕ
    # вопрос заново. Повторный вопрос — свидетельство, что ответ не
    # подошёл, и единственное, которое библиотека может получить, не
    # требуя от приложения ни строчки.
    #
    # ЗАЧЕМ ЭТО ВООБЩЕ. Сила растёт от извлечения (strength_use_step), но
    # растёт у ВСЕГО, что попало в выдачу, — верного и неверного одинаково.
    # Пока это так, любое ускорение подкрепления ускоряет и закрепление
    # ошибок, и замер это подтвердил: подъём шага с 0.05 до 0.15 выигрывал
    # на трёх стендах и проигрывал на четвёртом (раздел 2.16 аудита).
    # Недостаёт не скорости, а ОТРИЦАТЕЛЬНОЙ ветви.
    #
    # В мозге ошибка предсказания двусторонняя: всплеск дофамина на
    # неожиданную награду и ПРОВАЛ ниже фона на обещанную и не
    # случившуюся. У нас была только первая половина.
    #
    # 0.0 выключает.
    consequence_penalty: float = 0.0

    # --- МЕЧЕНИЕ И ЗАХВАТ (отложенное закрепление) ---
    #
    # Окно в секундах, в течение которого не прошедшее гейт событие может
    # быть закреплено задним числом сильным событием рядом. 0.0 выключает.
    #
    # БИОЛОГИЯ. Слабое воздействие ставит на синапсе МЕТКУ, но белков для
    # долговременного укрепления не хватает, и след угас бы. Если в
    # ближайший час-два рядом происходит сильное событие, клетка
    # производит эти белки на всю себя — и помеченный слабый синапс их
    # перехватывает (Фрей и Моррис, 1997). Слабая память закрепляется
    # ЗАДНИМ ЧИСЛОМ, за счёт того, что случилось рядом по времени.
    #
    # ЗАЧЕМ ЭТО НАМ. Гейт решает в момент события и необратимо: не прошло —
    # следа нет никогда. Предпочтения от этого страдают больше всего: «я
    # больше люблю кофе, чем чай» говорится спокойно, удивления не несёт и
    # порога не берёт. На трудном наборе LongMemEval это наш худший тип —
    # 20% R@1.
    #
    # ВАЖНО: ждёт метка не «положительной оценки», а ЛЮБОГО сильного
    # события. Знак не важен, важна интенсивность — так и в мозге, где
    # новизна, возбуждение и награда работают одинаково.
    tagging_window: float = 0.0

    # ИЗМЕРЕНО И ОТВЕРГНУТО, УМОЛЧАНИЕ НОЛЬ. При окне 900 с внешний
    # бенчмарк падает по всем типам сразу:
    #
    #     R@1 общий        65.0% -> 46.7%
    #     предпочтения       60% ->   40%
    #     многосессионные    74% ->   52%
    #     временные          58% ->   33%
    #
    # Захват записывает ВСЁ, что оказалось рядом со спайком, и стог
    # забивается. Это тот же эффект, что меряет стенд двойников: у
    # хранения есть цена, и платится она полнотой.
    #
    # ЗАОДНО ОТМЕНЕНО ОБОСНОВАНИЕ, ПОД КОТОРЫМ МЕХАНИЗМ ПЛАНИРОВАЛСЯ. Он
    # ставился в план как средство от потери предпочтений: «спокойно
    # сказанное не проходит гейт». Проверка показала обратное — гейт
    # пропускает содержательные фразы (плотность 0.500 при пороге 0.25
    # даже у зрелого организма), а предпочтения дают R@10 80%, то есть
    # запись В ПАМЯТИ ЕСТЬ и находится. Это был отказ ранжирования, и
    # починило его взвешивание слов по редкости (2.20): 20% -> 60% R@1.
    #
    # Механизм биологически верен и оставлен: он может окупиться там, где
    # гейт действительно строг — высокий порог, перегрузка, зрелый
    # словарь. Но включать его без нового замера нельзя.
    # Какую долю плотности сильного события получает захваченная метка.
    # Не единицу: закрепляется слабый след, а не копия сильного.
    tagging_capture_factor: float = 0.5
    # Сколько меток держать. Буфер в памяти процесса, а не в базе: след
    # ЛАБИЛЕН по определению, и переживать перезапуск ему незачем.
    tagging_buffer: int = 16

    # Насколько похожими должны быть два запроса подряд, чтобы считать
    # второй повтором первого.
    consequence_repeat_threshold: float = 0.8
    # Окно в секундах: через час тот же вопрос — уже не переспрашивание, а
    # новое обращение к теме.
    consequence_window: float = 600.0

    # ОГРАНИЧЕНИЕ, КОТОРОЕ НАДО ЗНАТЬ. Последствие видно только там, где
    # разговор продолжается. Если библиотеку используют как склад —
    # записали, через месяц прочитали, — повторных вопросов не бывает, и
    # механизм молчит. Он для диалоговых применений.


    # Сколько кандидатов брать из полнотекстового индекса при проверке на
    # устаревание. Раньше проверка сканировала ВСЮ базу и считала косинус
    # для каждого узла — при каждой записи.
    supersede_scan_limit: int = 200
