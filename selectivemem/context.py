"""
================================================================================
 CONTEXT.PY — Временной контекст: организм не начинается заново каждую реплику
================================================================================
ЧТО БЫЛО НЕ ТАК. Промежуток между репликами использовался ТОЛЬКО в
затухании. Для всего остального три минуты и три дня — одно и то же:
память не знала, продолжается разговор или прервался на неделю. Каждое
событие приходило в пустоту, а связи между соседями по времени ставились
окном из двух последних записей — заплаткой, не различающей «сказано
подряд» и «сказано через месяц».

ЧТО ЗДЕСЬ. Состояние, которое ДРЕЙФУЕТ по прошедшему времени. Каждое
событие сдвигает его в свою сторону; пауза ослабляет накопленное тем
сильнее, чем она длиннее.

КАК ИМЕННО ПАУЗА МЕНЯЕТ ФОН, И ЭТО НЕ ОЧЕВИДНО. Близость считается
косинусом, а он не зависит от длины вектора — значит одно лишь ослабление
НАПРАВЛЕНИЯ не меняет. Пауза работает иначе, двумя путями:

  * ослабленный фон легче перебивается следующим событием: после долгого
    молчания новая реплика задаёт направление почти одна;
  * когда от фона остаётся ничтожно мало, он сбрасывается совсем —
    разговор начинается с чистого листа.

То есть дрейф порождают СОБЫТИЯ, а пауза решает, насколько они властны
над фоном. Так это и устроено в модели: контекст сдвигается входящим, а
не течением времени самим по себе.

    контекст = контекст * exp(-пауза / полураспад) + вектор события

Это модель временного контекста Ховарда и Каханы. В исследованиях
свободного припоминания она объясняет два наблюдения сразу: почему,
вспомнив эпизод, человек чаще называет следующим соседа ПО ВРЕМЕНИ, и
почему припоминание вытаскивает за собой целый кусок того дня. Контекст
привязывается к следу при записи, а при извлечении восстанавливается — и
тянет за собой то, что записывалось на том же фоне.

СВОИХ ЧАСОВ ЗДЕСЬ НЕТ, И НЕ БУДЕТ. Дрейф считается от РАЗНИЦЫ между
отметками времени, которые передал вызывающий. Иначе библиотеку нельзя
вставить в игру, где время игровое, и нельзя дважды воспроизвести прогон —
а на воспроизводимость опираются и стенды, и реплеи.

ЧЕГО ЭТО НЕ ДЕЛАЕТ. Не решает, что важно. Ответ на прямой вопрос
ожидаем — то есть в контексте он ещё МЕНЕЕ удивителен, — и при этом важнее
всего сказанного. Контекст делает память связной, а не разборчивой.
================================================================================
"""

import logging
import math
from typing import Optional, Sequence

logger = logging.getLogger(__name__)


class TemporalContext:
    """
    Медленно меняющееся состояние, на фоне которого пишутся события.

    Живёт в памяти процесса и не сохраняется: это СОСТОЯНИЕ, а не знание.
    Проснувшись, организм не помнит, о чём шла речь неделю назад, — ровно
    как человек, вернувшийся к прерванному разговору.
    """

    def __init__(self, half_life: float = 1800.0):
        # За сколько секунд паузы контекст теряет половину себя. Полчаса:
        # реплики подряд остаются одним разговором, перерыв на обед — уже
        # наполовину другим, следующий день — почти чистым листом.
        self.half_life = max(1e-6, half_life)
        self._vector: Optional[list] = None
        self._last_seen: Optional[float] = None

    # ------------------------------------------------------------------
    @property
    def vector(self) -> Optional[list]:
        """Текущий контекст. None означает «фона ещё нет»."""
        return self._vector

    def advance(self, timestamp: float) -> float:
        """
        Продвинуть время до `timestamp`, ослабив контекст по паузе.

        Возвращает долю оставшегося: 1.0 — пауза нулевая, 0.0 — контекст
        стёрся целиком. Вызывающий может по этому числу судить, тот же
        это разговор или новый.
        """
        if self._last_seen is None:
            self._last_seen = timestamp
            return 1.0

        elapsed = max(0.0, timestamp - self._last_seen)
        self._last_seen = timestamp
        keep = math.exp(-elapsed / self.half_life)

        if self._vector is not None:
            if keep <= 1e-6:
                # Пауза столь велика, что от фона ничего не осталось.
                # Держать околонулевой вектор вредно: косинус к нему
                # шумит, а смысла в нём нет.
                self._vector = None
            else:
                self._vector = [v * keep for v in self._vector]
        return keep

    def absorb(self, item: Optional[Sequence[float]]) -> None:
        """Событие сдвигает контекст в свою сторону."""
        if item is None:
            return
        if self._vector is None:
            self._vector = [float(v) for v in item]
            return
        if len(item) != len(self._vector):
            # Кодировщик сменился на ходу — складывать нельзя, косинус
            # между разными пространствами не значит ничего.
            self._vector = [float(v) for v in item]
            return
        self._vector = [a + float(b) for a, b in zip(self._vector, item)]

    def similarity(self, other: Optional[Sequence[float]]) -> float:
        """Насколько другой контекст похож на нынешний, [0, 1]."""
        if self._vector is None or other is None or len(other) != len(self._vector):
            return 0.0
        # ОБЫЧНЫЙ float, А НЕ ТИП КОДИРОВЩИКА. Векторы приходят из numpy,
        # и произведение остаётся numpy.float32. SQLite таких типов не
        # знает и молча кладёт их в базу БАЙТАМИ — вес ребра переставал
        # быть числом, а падало это далеко от места ошибки, при первом же
        # сравнении веса с порогом.
        dot = float(sum(float(a) * float(b) for a, b in zip(self._vector, other)))
        na = math.sqrt(sum(float(a) * float(a) for a in self._vector))
        nb = math.sqrt(sum(float(b) * float(b) for b in other))
        if na <= 0.0 or nb <= 0.0:
            return 0.0
        return max(0.0, min(1.0, dot / (na * nb)))

    def snapshot(self) -> Optional[list]:
        """Копия контекста — чтобы привязать её к записываемому следу."""
        return list(self._vector) if self._vector is not None else None
