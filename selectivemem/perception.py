"""
================================================================================
 PERCEPTION.PY — Восприятие, которое организм отращивает сам
================================================================================
Мозг не рождается со смыслами. Он выводит их из того, что видит: слова,
встречающиеся в похожих окружениях, получают похожие представления. Именно
так устроены и все готовые векторные модели — просто их учат заранее и на
чужом корпусе.

ЗАЧЕМ СВОЁ, КОГДА ЕСТЬ ГОТОВОЕ. Затем, что готового может не быть.
Встроенная модель не добавляет к поиску ничего (замер: восемь пар из
шестнадцати решаются простым совпадением слов, и это ТЕ ЖЕ ВОСЕМЬ), а на
русском модель по умолчанию и вовсе шум — кот/бетон 0.803 против
кот/кошка 0.643. Многоязычная работает, но стоит гигабайт диска и полтора
оперативной, и обещание «ставится где угодно» на этом кончается.

А без различения смысла у нас не работает половина устройства: смысловое
удивление, обнаружение поправок, разделение образов. Организму нужны
чувства, и взять их неоткуда.

КАК ЭТО РАБОТАЕТ — СЛУЧАЙНОЕ ИНДЕКСИРОВАНИЕ.

Каждому слову даётся СЛУЧАЙНЫЙ разреженный вектор — его «отпечаток». Он
ничего не значит сам по себе и не меняется никогда.

Смысловой вектор слова складывается из отпечатков его СОСЕДЕЙ по тексту.
Слова, встречающиеся в похожих окружениях, набирают похожие суммы — и
сходятся, хотя ни разу не встретились рядом.

    «кот сидит на окне»      кот  += отпечаток(сидит) + отпечаток(окне)
    «кошка спит на диване»   кошка += отпечаток(спит) + отпечаток(диване)
    «кот пьёт молоко»        кот  += отпечаток(пьёт) + отпечаток(молоко)

После сотни фраз «кот» и «кошка» окажутся рядом, потому что оба стоят
перед глаголами действия и рядом с домашними предметами.

ЧЕМ ЭТО ХОРОШО ИМЕННО ЗДЕСЬ:

  * НИЧЕГО НЕ ТРЕБУЕТ. Ни обучения, ни видеокарты, ни зависимостей, ни
    загрузок. Чистый Python и стандартная библиотека.
  * СЧИТАЕТСЯ НА ЛЕТУ. Каждое сообщение дополняет представления; нет
    отдельной фазы обучения, как нет её и у мозга.
  * РАСТЁТ. Первые дни организм слеп, через тысячу сообщений начинает
    различать. Для проекта, заявляющего цифровой организм, это не
    недостаток, а свойство: восприятие развивается опытом.

ЧЕГО ОТ НЕГО ЖДАТЬ НЕ СТОИТ. Общего языка. Готовая модель видела
миллиарды слов, наш организм увидит тысячи, и на редких словах он будет
пуст. Но нам общий язык и не нужен: нам нужно различать темы ОДНОГО
человека, а там словарь маленький и повторяющийся.

ИЗМЕРЕНО, И РЕЗУЛЬТАТ ОТРИЦАТЕЛЬНЫЙ. ВЫКЛЮЧЕНО ПО УМОЛЧАНИЮ.

`tools/probe_semantic.py`, шестнадцать пар «факт → как о нём спросят»:

    встроенная модель                    9/16
    выращенное, без опыта                8/16   (то же, что совпадение слов)
    выращенное, 2303 показа              6/16
    выращенное, 6823 показа              6/16

Опыт не помогает, а мешает. Причина видна и она принципиальная: стенд
требует ОБЩЕГО ЗНАНИЯ ЯЗЫКА — что Python это язык программирования, что
«не ем мясо» значит «вегетарианец». Из тысяч фраз одного человека такое
не выводится, сколько их ни показывай. Готовая модель видела миллиарды.

ЧТО ВЫРАЩЕННОЕ УМЕЕТ. Различать темы, которые видело МНОГО РАЗ В РАЗНЫХ
ОКРУЖЕНИЯХ. Замер на чистом опыте: после 2360 показов кот/кошка +0.935,
кот/бетон +0.080 — разделение +0.855 там, где встроенная модель даёт
перевёрнутое −0.160. То есть механизм работает, но задача, которую решает
кодировщик в этой библиотеке, ему не по силам.

ПЕРВАЯ ВЕРСИЯ ПРОВАЛИЛАСЬ ЕЩЁ И ПО ДРУГОЙ ПРИЧИНЕ, и это стоит знать
всякому, кто возьмётся продолжать: обучающий поток был шаблоном со
случайной подстановкой («сегодня опять про {слово} говорили»), и все слова
попали в ОДИНАКОВОЕ окружение — то есть сошлись друг с другом. Замер
показал ухудшение 8 -> 6 -> 4 по мере «обучения». Методу нужно обратное:
у разных тем должны быть разные окружения.

И ТРЕТЬЕ, УСТРОЙСТВЕННОЕ. Включённое выращивание ОТКЛЮЧАЕТ готовую модель
— иначе векторы приходили бы из двух разных пространств, а косинус между
ними не значит ничего. Но это значит, что незрелый организм остаётся без
смысла ВОВСЕ, хотя рабочая модель под рукой. Пока эта развилка не решена,
включать выращивание по умолчанию нельзя.
================================================================================
"""

import logging
import math
import random
from array import array
from typing import Dict, List, Optional, Sequence

logger = logging.getLogger(__name__)


class GrownEncoder:
    """
    Восприятие, выращенное из опыта организма.

    Держится в памяти процесса и восстанавливается из графа слов при
    открытии базы: сами отпечатки детерминированы (порождаются от текста
    слова), поэтому одинаковый опыт даёт одинаковые векторы — это важно
    для игр, где нужен побайтово воспроизводимый результат.
    """

    def __init__(self, dimensions: int = 256, active: int = 8,
                 window: int = 3, decay: float = 1.0):
        # Размерность и число ненулевых позиций в отпечатке. Восемь из
        # двухсот пятидесяти шести — обычная разреженность для этого
        # метода: достаточно редко, чтобы случайные отпечатки почти не
        # пересекались, и достаточно часто, чтобы суммы не вырождались.
        self.dimensions = dimensions
        self.active = active
        # Сколько соседей слева и справа считать окружением. Три — то же
        # окно, что у нашего графа со-встречаемости.
        self.window = window
        # Во сколько раз слабее учитывается сосед через одно слово.
        self.decay = decay
        self._context: Dict[str, array] = {}
        self._seen: Dict[str, int] = {}

    # ------------------------------------------------------------------
    def _fingerprint(self, word: str) -> List[int]:
        """
        Отпечаток слова: какие позиции вектора он занимает и с каким
        знаком.

        ДЕТЕРМИНИРОВАН ОТ САМОГО СЛОВА, а не от счётчика: одинаковый опыт
        обязан давать одинаковые векторы, иначе теряется воспроизводимость,
        которую библиотека обещает играм и тестам.
        """
        rng = random.Random(hash_word(word))
        positions = rng.sample(range(self.dimensions), self.active)
        return [p if rng.random() < 0.5 else -p - 1 for p in positions]

    def observe(self, tokens: Sequence[str]) -> None:
        """
        Показать организму фразу: соседи оставляют след друг на друге.

        Ничего не возвращает и не требует. Это и есть всё обучение —
        никакой отдельной фазы нет, как нет её и у мозга.
        """
        if len(tokens) < 2:
            return
        for index, word in enumerate(tokens):
            vector = self._context.get(word)
            if vector is None:
                vector = array("f", [0.0]) * self.dimensions
                self._context[word] = vector
            self._seen[word] = self._seen.get(word, 0) + 1

            lo = max(0, index - self.window)
            hi = min(len(tokens), index + self.window + 1)
            for other in range(lo, hi):
                if other == index:
                    continue
                # Дальний сосед весит меньше ближнего — так же, как в
                # графе со-встречаемости, где ребро ставится только между
                # соседними словами.
                distance = abs(other - index)
                weight = self.decay ** (distance - 1)
                for slot in self._fingerprint(tokens[other]):
                    if slot >= 0:
                        vector[slot] += weight
                    else:
                        vector[-slot - 1] -= weight

    def encode(self, tokens: Sequence[str]) -> Optional[array]:
        """
        Вектор фразы — среднее по векторам её слов.

        None означает, что ни одно слово ещё не встречалось: организм
        этого не видел и представления не имеет. Честнее вернуть «не
        знаю», чем нулевой вектор, который потом окажется «похож» на всё.
        """
        known = [self._context[w] for w in tokens if w in self._context]
        if not known:
            return None
        total = array("f", [0.0]) * self.dimensions
        for vector in known:
            for i in range(self.dimensions):
                total[i] += vector[i]
        norm = math.sqrt(sum(v * v for v in total))
        if norm <= 0.0:
            return None
        return array("f", (v / norm for v in total))

    # ------------------------------------------------------------------
    @property
    def vocabulary(self) -> int:
        return len(self._context)

    @property
    def exposures(self) -> int:
        return sum(self._seen.values())

    def maturity(self, target: int = 1000) -> float:
        """
        Насколько восприятие созрело: 0 — новорождённый, 1 — насмотрелся.

        Нужна не для украшения. Пока восприятие незрело, опираться на него
        нельзя — смысловое удивление посчитает всё незнакомым, а
        обнаружение поправок промолчит. Приложение должно уметь спросить,
        готов ли организм различать.
        """
        return min(1.0, self.exposures / max(1, target))


def hash_word(word: str) -> int:
    """
    Устойчивый хеш слова.

    Встроенный hash() солится при каждом запуске, и векторы менялись бы от
    запуска к запуску — а библиотека обещает побайтовую воспроизводимость
    для реплеев и тестов.
    """
    value = 0
    for char in word:
        value = (value * 131 + ord(char)) & 0xFFFFFFFF
    return value
