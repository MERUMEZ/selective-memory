"""
================================================================================
 PERCEPTION.PY — Восприятие, которое организм отращивает сам
================================================================================
Мозг не рождается со смыслами. Он выводит их из того, что видит: слова,
встречающиеся в похожих окружениях, получают похожие представления. Именно
так устроены и все готовые векторные модели — просто их учат заранее и на
чужом корпусе.

ЗАЧЕМ СВОЁ, КОГДА ЕСТЬ ГОТОВОЕ. Затем, что готового может не быть.

Здесь стояло другое обоснование — «встроенная модель не добавляет к
поиску ничего». Оно было НЕВЕРНЫМ и держалось на подмене величин: число
пар, делящих хоть одно слово (8), выдавалось за число пар, которые решает
поиск по словам (5). Настоящий счёт — 9 против 5, встроенная модель даёт
четыре попадания. Стенд исправлен и считает базу прогоном.

Настоящих причин иметь своё две, и обе скромнее прежней.

  * МОДЕЛИ МОЖЕТ НЕ БЫТЬ. Не установлена, не тот язык, нет места на диске.
    Тогда выбор не «7 против 9», а «7 против 5» — и весь набор тестов на
    такой системе даёт 22 падения без восприятия против 2 с ним.
  * ЯЗЫК. Модель в пакете русская, и на русском она местами шум:
    кот/бетон 0.803 против кот/кошка 0.643. Многоязычная работает, но
    стоит гигабайт диска и полтора оперативной, и обещание «ставится где
    угодно» на этом кончается.

Без различения смысла не работает половина устройства: смысловое
удивление, обнаружение поправок, разделение образов.

КАК ЭТО РАБОТАЕТ — СЛУЧАЙНОЕ ИНДЕКСИРОВАНИЕ.

Каждому слову даётся СЛУЧАЙНЫЙ разреженный вектор — его «отпечаток». Он
ничего не значит сам по себе и не меняется никогда.

Смысловой вектор слова складывается из отпечатков его СОСЕДЕЙ по тексту.
Слова, встречающиеся в похожих окружениях, набирают похожие суммы — и
сходятся, хотя ни разу не встретились рядом.

    «кот сидит на окне»      кот  += отпечаток(сидит) + отпечаток(окне)
    «кошка спит на диване»   кошка += отпечаток(спит) + отпечаток(диване)
    «кот пьёт молоко»        кот  += отпечаток(пьёт) + отпечаток(молоко)

После сотни фраз «кот» и «кошка» окажутся рядом, потому что оба стоят
перед глаголами действия и рядом с домашними предметами.

ЧЕМ ЭТО ХОРОШО ИМЕННО ЗДЕСЬ:

  * НИЧЕГО НЕ ТРЕБУЕТ. Ни обучения, ни видеокарты, ни зависимостей, ни
    загрузок. Чистый Python и стандартная библиотека.
  * СЧИТАЕТСЯ НА ЛЕТУ. Каждое сообщение дополняет представления; нет
    отдельной фазы обучения, как нет её и у мозга.
  * РАСТЁТ. Первые дни организм слеп, через тысячу сообщений начинает
    различать. Для проекта, заявляющего цифровой организм, это не
    недостаток, а свойство: восприятие развивается опытом.

ЧЕГО ОТ НЕГО ЖДАТЬ НЕ СТОИТ. Общего языка. Готовая модель видела
миллиарды слов, наш организм увидит тысячи, и на редких словах он будет
пуст. Но нам общий язык и не нужен: нам нужно различать темы ОДНОГО
человека, а там словарь маленький и повторяющийся.

ИЗМЕРЕНО. ВКЛЮЧАЕТСЯ ЗАПАСНЫМ ВЫХОДОМ — КОГДА РАЗЛИЧАТЬ БОЛЬШЕ НЕЧЕМ.

`tools/probe_semantic.py`, шестнадцать пар «факт → как о нём спросят»:

    встроенная модель                    9/16
    выращенное, 973+ показов             7/16   (стабильно на трёх зёрнах)
    без семантики вовсе                  5/16

Отсюда правило включения. Там, где модель есть, выращенное её ЗАМЕНИЛО БЫ
(смешивать два пространства нельзя — косинус между ними ничего не значит)
и ухудшило бы поиск. Там, где модели нет, выбор стоит не между 7 и 9, а
между 7 и 5.

ЗАМЕР ВЕСОМЕЕ СТЕНДА — весь набор тестов на системе без модели:

    восприятие выключено                 22 падения
    восприятие выращивается               2 падения

Двадцать тестов, проверяющих смысловую работу, оживают. Оставшиеся два —
не поломки, а огрубление: выращенное связывает чуть шире, чем ждут два
теста, написанных под встроенную модель.

ДВА ДЕФЕКТА, НАЙДЕННЫЕ ПОСЛЕ ПЕРВОГО ЗАМЕРА. Первая версия давала 6/16 и
УХУДШАЛАСЬ с опытом. Причина была не в методе, а в двух местах, где я
написал ровно обратное тому, что уже доказано в этой же библиотеке:

  1. `encode` складывал векторы слов НЕНОРМИРОВАННЫМИ, а длина вектора
     растёт с числом встреч. Значит вклад слова во фразу был пропорционален
     его частоте — то есть фразу определяли служебные слова. Замер на живой
     речи: во фразе «я не ем мясо уже три года» вклад «уже» 13.5%, «не»
     12.4%, а «мясо» лишь 9.4%.
  2. Сосед оставлял след с весом 1 независимо от того, встречается он везде
     или редко. У всех слов накапливалась общая служебная составляющая:
     сходство заведомо НЕСВЯЗАННЫХ слов ползло +0.04 -> +0.12 за 2700
     показов.

Оба чинятся привыканием к частому (см. ниже по коду). Шум между чужими
фразами упал 0.174 -> 0.082, худший случай 0.700 -> 0.347.

И ТРЕТЬЕ, МЕТОДИЧЕСКОЕ. Первый обучающий поток был шаблоном со случайной
подстановкой («сегодня опять про {слово} говорили»), и все слова попали в
ОДИНАКОВОЕ окружение — то есть сошлись друг с другом. Замер показывал
ухудшение 8 -> 6 -> 4 «по мере обучения». Методу нужно обратное: у разных
тем должны быть разные окружения.

ЧЕГО ЖДАТЬ НЕ СТОИТ. Общего языка. Что Python — язык программирования, а
«не ем мясо» значит «вегетарианец», из тысяч фраз одного человека не
выводится. Готовая модель видела миллиарды слов, и там, где она есть, она
лучше.
================================================================================
"""

import logging
import math
import random
from array import array
from typing import Dict, List, Optional, Sequence

logger = logging.getLogger(__name__)


class GrownEncoder:
    """
    Восприятие, выращенное из опыта организма.

    Держится в памяти процесса и восстанавливается из графа слов при
    открытии базы: сами отпечатки детерминированы (порождаются от текста
    слова), поэтому одинаковый опыт даёт одинаковые векторы — это важно
    для игр, где нужен побайтово воспроизводимый результат.
    """

    def __init__(self, dimensions: int = 256, active: int = 8,
                 window: int = 3, decay: float = 1.0):
        # Размерность и число ненулевых позиций в отпечатке. Восемь из
        # двухсот пятидесяти шести — обычная разреженность для этого
        # метода: достаточно редко, чтобы случайные отпечатки почти не
        # пересекались, и достаточно часто, чтобы суммы не вырождались.
        self.dimensions = dimensions
        self.active = active
        # Сколько соседей слева и справа считать окружением. Три — то же
        # окно, что у нашего графа со-встречаемости.
        self.window = window
        # Во сколько раз слабее учитывается сосед через одно слово.
        self.decay = decay
        self._context: Dict[str, array] = {}
        self._seen: Dict[str, int] = {}

    # ------------------------------------------------------------------
    def _fingerprint(self, word: str) -> List[int]:
        """
        Отпечаток слова: какие позиции вектора он занимает и с каким
        знаком.

        ДЕТЕРМИНИРОВАН ОТ САМОГО СЛОВА, а не от счётчика: одинаковый опыт
        обязан давать одинаковые векторы, иначе теряется воспроизводимость,
        которую библиотека обещает играм и тестам.
        """
        rng = random.Random(hash_word(word))
        positions = rng.sample(range(self.dimensions), self.active)
        return [p if rng.random() < 0.5 else -p - 1 for p in positions]

    def observe(self, tokens: Sequence[str]) -> None:
        """
        Показать организму фразу: соседи оставляют след друг на друге.

        Ничего не возвращает и не требует. Это и есть всё обучение —
        никакой отдельной фазы нет, как нет её и у мозга.
        """
        if len(tokens) < 2:
            return
        # Счётчики поднимаем ОТДЕЛЬНЫМ ПРОХОДОМ, до накопления следов.
        # Иначе привыкание к соседу считалось бы по-разному слева и
        # справа: у соседа позади счётчик за эту же фразу уже поднят, у
        # соседа впереди — ещё нет, и вектор зависел бы от порядка слов
        # там, где не должен.
        for word in tokens:
            if word not in self._context:
                self._context[word] = array("f", [0.0]) * self.dimensions
            self._seen[word] = self._seen.get(word, 0) + 1

        for index, word in enumerate(tokens):
            vector = self._context[word]
            lo = max(0, index - self.window)
            hi = min(len(tokens), index + self.window + 1)
            for other in range(lo, hi):
                if other == index:
                    continue
                # Дальний сосед весит меньше ближнего — так же, как в
                # графе со-встречаемости, где ребро ставится только между
                # соседними словами.
                distance = abs(other - index)
                weight = self.decay ** (distance - 1)
                # ПРИВЫКАНИЕ. Сосед, встречающийся везде, не сообщает о
                # слове ничего: «на», «и», «это» стоят рядом со всем
                # подряд. Без этой поправки у каждого слова накапливается
                # одна и та же служебная составляющая, и все слова
                # съезжаются друг к другу — замер показывал ползущий вверх
                # пол сходства между заведомо несвязанными словами
                # (+0.04 -> +0.12 за 2700 показов).
                #
                # Нейрон отвечает на новый стимул и замолкает на
                # постоянном; здесь то же самое, только считаем на лету:
                # частоту соседа знаем лишь ту, что видели до сих пор.
                weight /= 1.0 + math.log1p(self._seen.get(tokens[other], 0))
                for slot in self._fingerprint(tokens[other]):
                    if slot >= 0:
                        vector[slot] += weight
                    else:
                        vector[-slot - 1] -= weight

    def encode(self, tokens: Sequence[str]) -> Optional[array]:
        """
        Вектор фразы — среднее по векторам её слов.

        None означает, что ни одно слово ещё не встречалось: организм
        этого не видел и представления не имеет. Честнее вернуть «не
        знаю», чем нулевой вектор, который потом окажется «похож» на всё.
        """
        known = [w for w in tokens if w in self._context]
        if not known:
            return None
        total = array("f", [0.0]) * self.dimensions
        for word in known:
            vector = self._context[word]
            # ДЛИНА ВЕКТОРА — НЕ ВАЖНОСТЬ СЛОВА. Она растёт просто с
            # числом встреч, поэтому без нормировки фразу определяет
            # самое частое слово, а частое — это служебное. Замер на
            # живой речи: во фразе «я не ем мясо уже почти три года»
            # вклад «уже» 13.5%, «не» 12.4%, а «мясо» лишь 9.4%.
            norm = math.sqrt(sum(v * v for v in vector))
            if norm <= 0.0:
                continue
            # РЕДКОЕ СЛОВО ГОВОРИТ О ФРАЗЕ БОЛЬШЕ ЧАСТОГО. Тот же вывод,
            # что уже подтверждён замером в поиске по совпадению слов
            # (_keyword_overlap взвешивает совпавшие слова по редкости);
            # восприятие было написано вопреки ему.
            weight = 1.0 / (1.0 + math.log1p(self._seen.get(word, 0)))
            scale = weight / norm
            for i in range(self.dimensions):
                total[i] += vector[i] * scale
        norm = math.sqrt(sum(v * v for v in total))
        if norm <= 0.0:
            return None
        return array("f", (v / norm for v in total))

    # ------------------------------------------------------------------
    @property
    def vocabulary(self) -> int:
        return len(self._context)

    @property
    def exposures(self) -> int:
        return sum(self._seen.values())

    def maturity(self, target: int = 1000) -> float:
        """
        Насколько восприятие созрело: 0 — новорождённый, 1 — насмотрелся.

        Нужна не для украшения. Пока восприятие незрело, опираться на него
        нельзя — смысловое удивление посчитает всё незнакомым, а
        обнаружение поправок промолчит. Приложение должно уметь спросить,
        готов ли организм различать.
        """
        return min(1.0, self.exposures / max(1, target))


def hash_word(word: str) -> int:
    """
    Устойчивый хеш слова.

    Встроенный hash() солится при каждом запуске, и векторы менялись бы от
    запуска к запуску — а библиотека обещает побайтовую воспроизводимость
    для реплеев и тестов.
    """
    value = 0
    for char in word:
        value = (value * 131 + ord(char)) & 0xFFFFFFFF
    return value
