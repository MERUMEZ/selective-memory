#: Слова, которые организм считает привычными ещё до первого разговора.
COMMON_WORDS: Set[str] = set(_RU) | set(_EN)

#: Какую привычность им приписывать. Единица означала бы «знаю назубок» и
#: закрывала бы им дорогу в темы навсегда; здесь чуть ниже — знание
#: априорное, и опыт вправе его поправить в обе стороны.
PRIOR_FAMILIARITY = 0.9


def prior_familiarity(word: str) -> float:
    """
    Насколько слово привычно ДО опыта. Ноль означает «не знаю такого».

    Вызывающий берёт максимум из этой оценки и той, что накопил граф
    языка: опыт добавляет знание, а не отменяет его.
    """
    return PRIOR_FAMILIARITY if word in COMMON_WORDS else 0.0
