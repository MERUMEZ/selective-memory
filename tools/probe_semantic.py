"""
================================================================================
 TOOLS/PROBE_SEMANTIC.PY — Найдёт ли память то, как человек реально спросит
================================================================================
Шестнадцать пар «факт — вопрос о нём». Половина пар НЕ ДЕЛИТ с фактом ни
одного слова: «где я живу» против «мы живём на Пушкина двенадцать». Это и
есть проверка семантики: совпадение слов такие случаи не вытянет.

ЗАЧЕМ ЭТОТ СТЕНД СУЩЕСТВУЕТ. Он отвечает на вопрос, который иначе решают
верой: даёт ли кодировщик хоть что-нибудь сверх совпадения слов.

    попаданий со встроенной моделью:             9 из 16
    попаданий тем же прогоном без семантики:     5 из 16
    пар, где есть хоть одно общее слово:         8 из 16

ОСТОРОЖНО С ПОСЛЕДНЕЙ СТРОКОЙ. Раньше стенд сравнивал попадания именно с
ней и подписывал её как «решаются совпадением слов». Это разные величины:
общее слово в паре ещё не значит, что поиск по словам вытащит верный узел
первым. На подмене был построен вывод «встроенная модель не даёт ничего»,
и он прожил в документации до тех пор, пока сравнение не сделали честным —
прогоном против прогона. Теперь стенд считает базу сам.

ПОКУПАТЕЛЮ: прогоните это на СВОЁМ домене и СВОЕЙ модели прежде, чем
встраивать. Замените FACTS и PROBES на свои — так вы узнаете качество
поиска за десять минут, а не через месяц эксплуатации.

Запуск:
    python tools/probe_semantic.py
    python tools/probe_semantic.py --no-semantics    # только слова
================================================================================
"""

import argparse
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

if "--logs" not in sys.argv:
    os.environ["LOG_LEVEL"] = "ERROR"

# Восемь фактов, какие человек рассказывает ассистенту о себе
FACTS = [
    "у меня аллергия на пенициллин",
    "моя дочь Лиза, ей шесть лет",
    "я предпочитаю Python, не Java",
    "я работаю бэкенд-разработчиком в финтехе",
    "мой рейс в Стамбул двадцатого мая",
    "я не ем мясо уже три года",
    "жену зовут Марина, у неё день рождения в апреле",
    "мы живём на Пушкина двенадцать, квартира сорок",
]

# Как он спросит о том же самом. Помечены пары, где НЕТ общих слов, —
# именно они отделяют настоящую семантику от совпадения по буквам.
PROBES = [
    ("какие у меня аллергии", 0),
    ("что мне нельзя принимать", 0),
    ("как зовут мою дочь", 1),
    ("сколько лет ребёнку", 1),
    ("на каком языке я пишу код", 2),
    ("какие языки программирования я люблю", 2),
    ("кем я работаю", 3),
    ("где я работаю", 3),
    ("когда я лечу", 4),
    ("куда у меня билет", 4),
    ("я вегетарианец?", 5),
    ("ем ли я мясо", 5),
    ("как зовут мою жену", 6),
    ("когда у Марины день рождения", 6),
    ("мой адрес", 7),
    ("где я живу", 7),
]


def main() -> None:
    parser = argparse.ArgumentParser(description="Качество поиска на реальных вопросах")
    parser.add_argument("--no-semantics", action="store_true",
                        help="отключить кодировщик: видно, сколько даёт совпадение слов")
    parser.add_argument("--logs", action="store_true")
    args = parser.parse_args()

    from selectivemem import Memory
    from selectivemem.graph_memory import MemoryGraph

    encoder = (lambda text: None) if args.no_semantics else None
    memory = Memory(":memory:", encoder=encoder)

    node_ids = [memory.observe(fact, emotion=0.9).node_id for fact in FACTS]

    # Сколько пар вообще решаются совпадением слов — это нижняя граница,
    # ниже которой семантика не даёт НИЧЕГО.
    graph: MemoryGraph = memory.graph
    fact_keywords = [graph._extract_keywords(f.lower()) for f in FACTS]
    lexical_solvable = sum(
        1 for query, target in PROBES
        if graph._extract_keywords(query.lower()) & fact_keywords[target]
    )

    hits = 0
    print("=" * 78)
    print(" НАЙДЁТ ЛИ ПАМЯТЬ ТО, КАК ЧЕЛОВЕК РЕАЛЬНО СПРОСИТ")
    print("=" * 78)
    for query, target in PROBES:
        found = memory.recall(query, top_k=1, with_associations=False)
        ok = bool(found) and found[0].id == node_ids[target]
        hits += ok
        got = found[0].context[:38] if found else "— ничего"
        print(f"  {'+' if ok else '.'} {query:38} -> {got}")

    total = len(PROBES)
    print("-" * 78)
    print(f" Попаданий: {hits} из {total} = {hits / total:.0%}")
    print(f" Пар, где есть хоть одно общее слово: {lexical_solvable}")

    # НАСТОЯЩАЯ БАЗА СРАВНЕНИЯ — ПРОГОН, А НЕ ПОДСЧЁТ ПАР.
    #
    # Здесь стояло сравнение с числом пар, делящих слово, и оно
    # подписывалось как «решаются совпадением слов». Это разные величины:
    # общее слово в паре ещё не значит, что поиск по словам вытащит
    # верный узел первым. Замер: пар с общим словом 8, а поиск без
    # семантики берёт 5. На этой подмене был сделан вывод «встроенная
    # модель не даёт ничего сверх слов» — при её настоящих 9 против 5.
    if not args.no_semantics:
        control = Memory(":memory:", encoder=lambda text: None)
        control_ids = [control.observe(f, emotion=0.9).node_id for f in FACTS]
        lexical_hits = 0
        for query, target in PROBES:
            got = control.recall(query, top_k=1, with_associations=False)
            lexical_hits += bool(got) and got[0].id == control_ids[target]
        control.close()
        print(f" Тот же прогон БЕЗ семантики:              {lexical_hits}")
        gain = hits - lexical_hits
        print(f" Кодировщик добавил:                       {gain:+d}")
        if gain <= 0:
            print()
            print(" ВНИМАНИЕ: семантика не добавила НИЧЕГО сверх совпадения слов.")
            print(" Крутить веса и пороги в таком случае бесполезно — различать")
            print(" нечем, дело в модели. См. раздел про кодировщик в README.")
    print("=" * 78)

    memory.close()


if __name__ == "__main__":
    main()
