"""
================================================================================
 TOOLS/COMPARE_GIST.PY — Что остаётся, когда подробности вытеснены
================================================================================
ВОПРОС, НА КОТОРЫЙ ОТВЕЧАЕТ СТЕНД. Память переполнилась, слабейшие эпизоды
вытеснены насовсем. Сколько мы на этом теряем — и спасает ли что-нибудь
кора, которая должна была успеть вывести из подробностей суть?

Это не украшение, а проверка главного обещания устройства. У живого
деталь и суть стареют по-разному: через год вы не помните, КАКИМИ СЛОВАМИ
вам сказали, что коллега переехал в Питер, но что он в Питере — помните.
Если у нас вытеснение просто отнимает, то забывание остаётся потерей и
никогда не становится сжатием.

ИЗМЕРЕНО (5 тем по 5 эпизодов, 300 реплик постороннего потока):

    ёмкость   с корой   без коры
        25      5 / 5      4 / 5
        15      4 / 5      4 / 5
        10      3 / 5      2 / 5
         6      3 / 5      2 / 5
         3      2 / 5      1 / 5

Забывание ДЕЙСТВИТЕЛЬНО становится сжатием: при жестокой тесноте кора
удерживает вдвое больше тем, чем остаётся в гиппокампе. Но удерживает она
РОВНО ОДНУ тему из пяти — прибавка не растёт с давлением, а держится на
единице.

И ВТОРАЯ БЕДА, КРУПНЕЕ ПЕРВОЙ: кора обобщает шум охотнее смысла.

    ёмкость 25: фактов 9, настоящих тем 2, мусора 7
    ёмкость 10: фактов 5, настоящих тем 1, мусора 4

Мусор — обрывки канцелярских фраз наполнителя: 'рано утром', 'прислал
счёт', 'записку неделе оставил прошлой' (слова ещё и переставлены, потому
что тема берётся пересечением множеств). Механизм не различает
повторяющуюся ТЕМУ и повторяющийся ОБОРОТ РЕЧИ.

ТРИ УСЛОВИЯ, И СРЕДНЕЕ ВАЖНЕЕ КРАЙНИХ:

    без предела ёмкости        — верхняя граница, ничего не терялось
    ёмкость + кора обобщает    — сколько удержали
    ёмкость, обобщение выкл.   — сколько удержали БЕЗ коры

Разница двух последних и есть вклад коры. Без третьего условия стенд
показывал бы «сколько помним», но не «благодаря чему».

ПРО ЭМОЦИЮ. Тематические эпизоды подаются БЕЗ надбавки значимости. С
emotion=0.9 они получали высокий вес, вытеснение их не трогало, и стенд
показывал одинаковые числа во всех трёх условиях — то есть мерил память,
из которой ничего не пропало. Проверять сжатие можно только на том, что
действительно вытесняется.

ПРО ВОПРОСЫ. Они делят с темой её слово. Вопросы без общих слов («откуда
я родом» против «вырос в новосибирске») эта система не берёт ВООБЩЕ — ни
с ёмкостью, ни без, — и на них стенд мерил бы слабость кодировщика, а не
потерю от вытеснения. Это отдельная беда, и у неё есть свой стенд
(probe_semantic).

ПРО ДАННЫЕ. Каждая тема подаётся НЕСКОЛЬКИМИ РАЗНЫМИ фразами, делящими
одно тематическое слово. Иначе обобщение не срабатывает вовсе: кора
выводит тему из повторяемости, а двадцать одинаковых строк — это одна
строка, повторённая двадцать раз. На вырожденных данных этот проект
стоял семь раз, поэтому фразы здесь собираются из непересекающихся
оборотов.

Запуск:
    python tools/compare_gist.py
    python tools/compare_gist.py --capacity 40
================================================================================
"""

