# Посторонний поток: он и вытесняет подробности, создавая тесноту.
FILLER_WHO = ["курьер", "сосед", "мастер", "коллега", "администратор", "водитель"]
FILLER_DID = ["перезвонил", "перенёс встречу", "прислал счёт",
              "предупредил заранее", "опоздал на час", "оставил записку"]
FILLER_WHEN = ["во вторник", "к вечеру", "перед обедом",
               "на прошлой неделе", "рано утром", "в конце месяца"]


def filler(rng):
    return f"{rng.choice(FILLER_WHO)} {rng.choice(FILLER_DID)} {rng.choice(FILLER_WHEN)}"


# Как часто хозяин прибирается. ОБЯЗАТЕЛЬНО: вытеснение по ёмкости живёт
# внутри forget(), у библиотеки нет планировщика и она не заводит потоков.
# Первая версия стенда его не звала — и показывала 42 эпизода при ёмкости
# 30, то есть мерила память, в которой вытеснение НИ РАЗУ НЕ СРАБОТАЛО.
FORGET_EVERY = 20
HOUR = 3600.0


def build(capacity: int, generalise: bool, filler_count: int):
    """Прожить жизнь: сначала темы, потом поток посторонних дел.

    Время идёт, и хозяин время от времени прибирается — иначе ни
    затухание, ни вытеснение не работают вовсе.
    """
    settings = MemorySettings()
    settings.memory_capacity = capacity
    if not generalise:
        # Ноль выключает вывод темы из повторяющегося.
        settings.cortex_fact_threshold = 0
    memory = Memory(":memory:", settings=settings)

    # 1. Темы — вперемешку, чтобы повторы одной темы не шли подряд.
    events = [(word, line) for word, (lines, _) in THEMES.items() for line in lines]
    rng = random.Random(17)
    rng.shuffle(events)

    clock = 0.0
    seen = 0

    def live(text: str, emotion: float = 0.0) -> None:
        nonlocal clock, seen
        memory.observe(text, emotion=emotion, timestamp=clock)
        clock += HOUR
        seen += 1
        if seen % FORGET_EVERY == 0:
            memory.forget(now=clock)

    for _, line in events:
        live(line)

    # 2. Посторонний поток — он и создаёт тесноту.
    for _ in range(filler_count):
        live(filler(rng))

    memory.forget(now=clock)
    return memory, settings, clock


def probe(memory, clock: float) -> tuple:
    """Спросить о каждой теме словами, которых в эпизодах не было."""
    hits_1 = hits_5 = 0
    for word, (_, question) in THEMES.items():
        found = memory.recall(question, top_k=5, with_associations=False,
                              timestamp=clock)
        texts = [(m.context or "").lower() for m in found]
        hits_1 += bool(texts) and word in texts[0]
        hits_5 += any(word in t for t in texts)
    return hits_1, hits_5


def main() -> None:
    parser = argparse.ArgumentParser(description="Что остаётся после вытеснения")
    parser.add_argument("--capacity", type=int, default=30)
    parser.add_argument("--filler", type=int, default=200)
    parser.add_argument("--logs", action="store_true")
    args = parser.parse_args()

    total = len(THEMES)
    print("=" * 78)
    print(" ЧТО ОСТАЁТСЯ, КОГДА ПОДРОБНОСТИ ВЫТЕСНЕНЫ")
    print("=" * 78)
    print(f" Тем: {total}, эпизодов на тему: {len(next(iter(THEMES.values()))[0])}, "
          f"постороннего потока: {args.filler}")
    print(f" Ёмкость в опытах со стеснением: {args.capacity}")
    print("-" * 78)
    print(f"  {'условие':30} {'эпизодов':>9} {'фактов':>7} | {'R@1':>5} {'R@5':>5}")
    print("  " + "-" * 62)

    rows = [
        ("без предела ёмкости", 0, True),
        (f"ёмкость {args.capacity}, кора обобщает", args.capacity, True),
        (f"ёмкость {args.capacity}, обобщение выкл.", args.capacity, False),
    ]
    results = {}
    for label, capacity, generalise in rows:
        memory, settings, clock = build(capacity, generalise, args.filler)
        episodes = memory.graph.gate.episodic.count()
        facts = len(memory.graph.gate.semantic.facts(limit=1000))
        h1, h5 = probe(memory, clock)
        results[label] = (h1, h5)
        print(f"  {label:30} {episodes:9d} {facts:7d} | "
              f"{h1}/{total:<3} {h5}/{total}")
        memory.close()

    print()
    with_cortex = results[f"ёмкость {args.capacity}, кора обобщает"]
    without = results[f"ёмкость {args.capacity}, обобщение выкл."]
    print(f" ВКЛАД КОРЫ: R@1 {without[0]} -> {with_cortex[0]}, "
          f"R@5 {without[1]} -> {with_cortex[1]} (из {total})")
    print()
    print(" Если оба числа равны, кора не спасает НИЧЕГО, и забывание")
    print(" остаётся потерей, а не сжатием.")
    print("=" * 78)


if __name__ == "__main__":
    main()
