"""
================================================================================
 TOOLS/COMPARE_INTEROCEPTION.PY — Чувствует ли организм собственное состояние
================================================================================
Проверяются ДВЕ РАЗНЫЕ ВЕЩИ, и путать их нельзя.

  1. ШЕВЕЛИТСЯ ЛИ СОСТОЯНИЕ ОСМЫСЛЕННО. Организм в тесноте обязан
     отличаться от просторного, в бессвязном потоке — от предсказуемого,
     под градом поправок — от согласованного. Если три условия дают одно
     и то же число, никакого самочувствия нет, есть украшение.

  2. МЕНЯЕТ ЛИ ОНО ПОВЕДЕНИЕ ПАМЯТИ. Состояние идёт в гейт по двум
     каналам: срочность запись облегчает, напряжение затрудняет. Значит
     доля записанного должна РАСХОДИТЬСЯ между условиями — и расходиться
     в предсказанную сторону, а не абы как.

Второе важнее первого: величина, которая красиво меняется и ни на что не
влияет, в этом проекте уже встречалась (энтропия Шеннона считалась и
никого не трогала).

Запуск:
    python tools/compare_interoception.py
================================================================================
"""

import os
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

if "--logs" not in sys.argv:
    os.environ["LOG_LEVEL"] = "ERROR"

from selectivemem import Memory
from selectivemem.settings import MemorySettings
from dataclasses import dataclass


@dataclass
class Shares:
    """Доли записанного, разнесённые по пути попадания в память."""
    gate: float
    supersede: float

    @property
    def total(self) -> float:
        return self.gate + self.supersede

# ----------------------------------------------------------------------
# ЧЕТЫРЕ СРЕДЫ — ГЕНЕРАТОРАМИ, А НЕ СПИСКАМИ.
#
# Первая версия держала списки строк и гоняла их по кругу. Это НЕ РАБОТАЕТ
# для проверки удивления: восемь строк тарабарщины, повторённые восемь
# раз, к третьему кругу становятся привычными, и «бессвязная» среда
# показывала удивление 0.00 наравне с предсказуемой. Мерился редкий
# словарь, а не бессвязность.
#
# Правильная бессвязная среда обязана порождать НОВОЕ каждый раз — тогда
# удивление остаётся высоким сколь угодно долго, как и положено миру,
# который не поддаётся предсказанию.
# ----------------------------------------------------------------------

_SLOTS = ["утром", "днём", "вечером", "ночью"]
_DRINKS = ["чай", "кофе", "какао", "компот"]


def predictable(rng):
    """Один и тот же уклад: слова быстро становятся привычными."""
    return f"{rng.choice(_SLOTS)} я пил {rng.choice(_DRINKS)} на кухне"


_WHO = ["сосед", "врач", "курьер", "мастер", "сестра", "напарник"]
_DID = ["позвонил", "приехал", "предупредил", "опоздал", "починил", "принёс"]
_WHEN = ["во вторник", "к обеду", "под вечер", "на выходных", "перед отпуском"]
_WHAT = ["насчёт крыши", "из-за трубы", "по поводу счётчика",
         "с новым ключом", "про очередь", "за инструментом"]


def varied(rng):
    """Знакомые слова в новых сочетаниях: посильная новизна."""
    return (f"{rng.choice(_WHO)} {rng.choice(_DID)} {rng.choice(_WHEN)} "
            f"{rng.choice(_WHAT)}")


_CONS = "бвгджзклмнпрстфхцчшщ"
_VOW = "аеиоуыэюя"


def chaotic(rng):
    """Каждый раз новые слова: мир, который не поддаётся предсказанию."""
    def word():
        return "".join(
            rng.choice(_CONS) + rng.choice(_VOW)
            for _ in range(rng.randint(2, 4))
        )
    return " ".join(word() for _ in range(rng.randint(4, 6)))


_NAMES = ["Рекс", "Бобик", "Шарик", "Тузик", "Полкан", "Мухтар",
          "Дружок", "Барсик", "Граф", "Найда", "Джек", "Веста"]


def contradictions(rng):
    """Каждая строка отменяет предыдущую: модель мира не держится."""
    return f"мою собаку зовут {rng.choice(_NAMES)}"


# Сколько кругов идёт на обживание. ОБЯЗАТЕЛЬНО, и вот почему: в первом
# круге организму ново ВСЁ, поэтому пишется каждая строка независимо от
# самочувствия. Первая версия стенда считала долю по всему прогону и
# показывала одинаковые 16.7% в трёх средах из пяти — ровно 8 записей
# первого круга из 48 строк. То есть мерился переходный процесс, а
# установившееся поведение не мерилось вовсе.
WARMUP_ROUNDS = 2
# Сколько событий в круге.
BATCH = 8


def run(name: str, stream, rounds: int, capacity: int = 0, intrinsic: bool = True):
    """Прогнать поток и вернуть самочувствие и долю записанного.

    Доля считается ТОЛЬКО по кругам после обживания.
    """
    settings = MemorySettings()
    settings.intrinsic_emotion = intrinsic
    settings.memory_capacity = capacity
    memory = Memory(":memory:", settings=settings)

    rng = random.Random(5)
    by_gate = 0
    by_supersede = 0
    total = 0
    for round_index in range(rounds):
        counted = round_index >= WARMUP_ROUNDS
        for _ in range(BATCH):
            result = memory.observe(stream(rng))
            if counted:
                total += 1
                if result.node_id is not None:
                    # ДВА РАЗНЫХ ИСТОЧНИКА ЗАПИСИ, и смешивать их нельзя.
                    # Поправка пишется В ОБХОД гейта: она по природе не
                    # удивляет и порога не берёт. Значит доля записанного
                    # НЕ измеряет работу гейта, пока эти два пути не
                    # разделены, — а именно по ней здесь и судят.
                    if result.superseded_ids:
                        by_supersede += 1
                    else:
                        by_gate += 1

    state = memory.feel()
    memory.close()
    return name, state, Shares(
        gate=by_gate / total if total else 0.0,
        supersede=by_supersede / total if total else 0.0,
    )


def main() -> None:
    print("=" * 78)
    print(" ЧУВСТВУЕТ ЛИ ОРГАНИЗМ СОБСТВЕННОЕ СОСТОЯНИЕ")
    print("=" * 78)

    rows = [
        run("предсказуемое", predictable, rounds=10),
        run("разнообразное", varied, rounds=10),
        run("бессвязное", chaotic, rounds=10),
        run("поток поправок", contradictions, rounds=10),
        run("теснота (ёмкость 5)", varied, rounds=10, capacity=5),
    ]

    head = (f"  {'среда':22} {'тесн':>5} {'удивл':>6} {'непост':>7} {'рассог':>7}"
            f" | {'СРОЧН':>6} {'НАПРЯЖ':>7} | {'гейт':>6} {'поправк':>8}")
    print(head)
    print("  " + "-" * (len(head) - 2))
    for name, state, share in rows:
        print(
            f"  {name:22} {state.crowding:5.2f} {state.mean_surprise:6.2f} "
            f"{state.comprehensibility_error:7.2f} {state.coherence_error:7.2f} | "
            f"{state.urgency:6.2f} {state.strain:7.2f} | "
            f"{share.gate:5.1%} {share.supersede:8.1%}"
        )

    print()
    print(" ЧТО ДОЛЖНО БЫТЬ ВИДНО:")
    print("   * бессвязное и предсказуемое — оба далеки от посильной новизны,")
    print("     но с РАЗНЫХ сторон, и оба поднимают напряжение;")
    print("   * поток поправок поднимает СРОЧНОСТЬ, а не напряжение;")
    print("   * теснота поднимает напряжение при том же потоке слов;")
    print("   * доля записанного расходится вслед за каналами.")

    # ------------------------------------------------------------------
    # Влияние на поведение: тот же поток с внутренней средой и без неё.
    # ------------------------------------------------------------------
    print()
    print("=" * 78)
    print(" ВЛИЯЕТ ЛИ ЭТО НА ПАМЯТЬ: тот же поток, среда включена и выключена")
    print("=" * 78)
    print(f"  {'среда':22} {'через гейт: без':>16} {'с внутр.':>10} "
          f"{'разница':>10}")
    print("  " + "-" * 62)
    for label, stream, rounds, capacity in [
        ("предсказуемое", predictable, 10, 0),
        ("разнообразное", varied, 10, 0),
        ("бессвязное", chaotic, 10, 0),
        ("поток поправок", contradictions, 10, 0),
        ("теснота (ёмкость 5)", varied, 10, 5),
    ]:
        _, _, base = run(label, stream, rounds, capacity, intrinsic=False)
        _, _, share = run(label, stream, rounds, capacity, intrinsic=True)
        # Сравниваются ТОЛЬКО записи через гейт: на него и влияет
        # внутренняя среда, а ветка поправок его не спрашивает.
        delta = (share.gate - base.gate) * 100.0
        print(f"  {label:22} {base.gate:15.1%} {share.gate:9.1%} "
              f"{delta:+8.1f} п.п.")
    print("=" * 78)


if __name__ == "__main__":
    main()
