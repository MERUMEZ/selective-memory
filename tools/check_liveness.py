from selectivemem import Memory, MemorySettings  # noqa: E402

DAY = 86400.0

# Метки в логах, по которым видно срабатывание. Ключ — читаемое имя
# механизма, значение — фрагмент, который он печатает.
MARKERS = {
    "запись (спайк-гейт)": "[MEMORY SAVED]",
    "угасание": "[DECAY APPLIED]",
    "вытеснение устаревшего": "[SUPERSEDED]",
    "растекание активации": "[ASSOCIATION]",
    "переупорядочивание": "[RERANK]",
    "вытеснение по ёмкости": "[CAPACITY]",
    "консолидация": "[CONSOLIDATION]",
    "подрезка связей": "[EDGE DECAY APPLIED]",
    # СОН. Добавлены после того, как первая версия стенда объявила "все
    # механизмы живы", проверив только те восемь, что я вспомнил при
    # написании. Инструмент, созданный ловить слепые зоны, имел
    # собственную: подрезка, поиск хабов и абстрактные узлы в список не
    # попали. Отсюда правило — список механизмов сверяется с кодом, а не
    # с памятью.
    "синаптическая подрезка": "[SLEEP PRUNING]",
    "поиск хаб-кластеров": "[SLEEP CLUSTER]",
    "абстрактные узлы": "[SLEEP CONSOLIDATION]",
}

TOPICS = [
    "меня зовут Паша и я работаю программистом",
    "у меня аллергия на пенициллин",
    "моя собака зовут Рекс",
    "я живу в городе у реки",
    "мой отпуск начинается в июле",
    "я не ем мясо уже пять лет",
]

# Противоречия — чтобы проверить вытеснение устаревшего.
UPDATES = [
    "мою собаку теперь зовут Бобик",
    "я переехал в другой город",
]

# РАЗГОВОР ДОЛЖЕН БЫТЬ НАСЫЩЕННЫМ, иначе стенд не даёт механизмам шанса.
# Первая версия крутила шесть коротких фраз по кругу; словарь вырождался
# за десяток реплик, среднее удивление падало до 0.12 при пороге свёртки
# 0.55, и консолидация честно решала "рутинный шум" в 100% случаев.
# Стенд объявлял её работающей вхолостую — но виноват был он сам.
#
# На настоящем разговоре (LongMemEval) медиана удивления эпизода 0.523.
FILLER = [
    "сосед сверху затеял ремонт и сверлит по вечерам",
    "синоптики обещают ясную погоду на все выходные",
    "надо наконец разобрать кладовку и выкинуть старые лыжи",
    "цены в магазине у дома выросли почти на четверть",
    "во дворе поставили новую лавочку возле детской площадки",
    "лифт починили только к среде, три дня ходили пешком",
    "в парке зацвели каштаны, впервые за несколько лет",
    "почтальон принёс извещение о заказном письме",
    "водитель автобуса объявил, что маршрут изменили",
    "врач в поликлинике выписал направление на анализы",
    "продавец рассказал про новую партию сыра из Адыгеи",
    "сантехник обещал прийти в четверг после обеда",
    "объявление на двери подъезда провисело две недели",
    "стройка за домом наконец закончилась и стало тише",
]


# ИСХОДЫ, А НЕ ВЫЗОВЫ. Стенд считал срабатывания и объявлял механизм
# живым, если тот хоть раз отработал. Но механизм может честно
# отрабатывать и КАЖДЫЙ РАЗ решать "ничего не делать" — консолидация так
# и вела себя, принимая решение "рутинный шум" в 100% случаев, и стенд
# был доволен. Разбирательство заняло часы.
#
# Поэтому метки поделены: одни означают "механизм позвали", другие —
# "механизм что-то СДЕЛАЛ". Ноль во второй колонке при ненулевой первой
# и есть тот случай, который раньше был невидим.
OUTCOME_MARKERS = {
    # ОБА ИСХОДА ПЕРЕЧИСЛЕНЫ ЯВНО. Первая версия ловила только
    # "Structural node" и объявляла консолидацию работающей вхолостую,
    # тогда как та исправно писала ЭМОЦИОНАЛЬНЫЕ узлы, — инструмент
    # считал успех неудачей.
    #
    # Вторая версия ловила просто "[CONSOLIDATION] " и стала засчитывать
    # строку "Skipped" как работу, то есть проверка превратилась в
    # показную. Перечисление обязано быть точным: исход — это созданный
    # узел, а не любое упоминание механизма.
    "консолидация": ("[CONSOLIDATION] Emotional node",
                     "[CONSOLIDATION] Structural node"),
    "синаптическая подрезка": "edges, ",
    "вытеснение по ёмкости": "[CAPACITY]",
    "вытеснение устаревшего": "[SUPERSEDED]",
    "абстрактные узлы": "[SLEEP CONSOLIDATION] Abstract",
}


class MarkerCounter(logging.Handler):
    """Считает, сколько раз в логах мелькнула каждая метка."""

    def __init__(self):
        super().__init__(level=logging.DEBUG)
        self.counts: Dict[str, int] = collections.Counter()

    def emit(self, record):
        try:
            text = record.getMessage()
        except Exception:
            return
        for name, marker in MARKERS.items():
            if marker in text:
                self.counts[name] += 1
        for name, marker in OUTCOME_MARKERS.items():
            variants = marker if isinstance(marker, tuple) else (marker,)
            if any(v in text for v in variants):
                self.counts["исход:" + name] += 1


def run(messages: int, seed: int) -> Dict[str, int]:
    rng = random.Random(seed)
    counter = MarkerCounter()
    root = logging.getLogger("selectivemem")
    root.setLevel(logging.DEBUG)
    root.addHandler(counter)

    now = [1_700_000_000.0]
    settings = MemorySettings(
        # Всё, что мы починили за эти сутки, ВКЛЮЧЕНО: стенд отвечает на
        # вопрос "жив ли механизм, когда его не выключили", а не "жив ли
        # он при умолчаниях".
        associate_recalled_limit=3,
        rerank_band=0.05,
        # ЁМКОСТЬ ОБЯЗАНА БЫТЬ НИЖЕ ЧИСЛА ЗАПИСЕЙ, иначе стенд объявляет
        # вытеснение мёртвым, ничего о нём не узнав. Здесь стояло 40 при
        # 32 записанных узлах — вытеснять было нечего, и проверка выпуска
        # краснела на исправном механизме.
        #
        # Причина в том, что порог сдвинулся под стендом: движок стал
        # избирательнее (внутренняя среда, умножение вместо сложения), и
        # число записей упало ниже ёмкости, подобранной когда-то под
        # прежнюю долю. Замер на 80 сообщениях, 32 записи:
        #
        #     ёмкость 40 -> 0 вытеснений
        #     ёмкость 20 -> 4
        #     ёмкость 10 -> 7
        memory_capacity=20,
        delete_on_decay=False,
        contradiction_search_threshold=0.5,
        consolidate_from_stm=True,
    )
    memory = Memory(":memory:", settings=settings, clock=lambda: now[0])

    stream = TOPICS + FILLER * 3 + UPDATES + FILLER * 3
    rng.shuffle(stream)
    stream = (stream * 10)[:messages]

    for index, text in enumerate(stream, start=1):
        memory.context_for(text, top_k=3)
        memory.observe(text, response="понятно", emotion=0.6)
        if index % 5 == 0:
            memory.feedback(+1.0)
        now[0] += 300.0
        if index % 10 == 0:
            now[0] += 6 * 3600.0
            memory.forget(now=now[0])

    now[0] += 3 * DAY
    memory.forget(now=now[0])
    # Сон вызывается ЯВНО, как forget: у библиотеки нет планировщика и она
    # не заводит потоков. Приложение само решает, когда простаивает.
    memory.sleep(timestamp=now[0])
    memory.recall("что ты обо мне помнишь", top_k=5)

    memory.close()
    root.removeHandler(counter)
    return counter.counts


def main() -> None:
    parser = argparse.ArgumentParser(description="Срабатывает ли каждый механизм")
    parser.add_argument("--messages", type=int, default=80)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    counts = run(args.messages, args.seed)

    print("=" * 70)
    print(" ЖИВУЧЕСТЬ МЕХАНИЗМОВ")
    print("=" * 70)
    print(f" Разговор из {args.messages} сообщений, затем 3 суток молчания.")
    print("-" * 70)

    dead, idle = [], []
    for name in MARKERS:
        hits = counts.get(name, 0)
        mark = "мёртв" if hits == 0 else f"{hits}"
        if hits == 0:
            dead.append(name)
        outcome = counts.get("исход:" + name)
        suffix = "" if name not in OUTCOME_MARKERS else (
            f"   из них сделали: {outcome or 0}"
        )
        if name in OUTCOME_MARKERS and hits and not outcome:
            suffix += "  <- ВЫЗЫВАЕТСЯ, НО НИЧЕГО НЕ ДЕЛАЕТ"
            idle.append(name)
        print(f" {name:28} {mark:>10}{suffix}")

    print("=" * 70)
    if dead:
        print(f" МЁРТВЫХ МЕХАНИЗМОВ: {len(dead)}")
        for name in dead:
            print(f"   - {name}")
    if idle:
        print(f" ВХОЛОСТУЮ РАБОТАЮТ: {len(idle)}")
        for name in idle:
            print(f"   - {name}")
        print(" Такой механизм неотличим от живого, если считать только вызовы.")
    if dead or idle:
        sys.exit(1)
    print(" Все механизмы срабатывают и делают работу.")


if __name__ == "__main__":
    main()
